#!/usr/bin/env python3
"""Derive a macOS 13 / Intel hash lock from the upstream x86_64 lock.

PySide6 6.12.0 only ships ``macosx_14_0_universal2`` wheels, so it cannot be
installed on macOS 13. PySide6 6.11.3 is the last release whose macOS wheels
are tagged ``macosx_13_0_universal2`` (x86_64 + arm64), which covers Intel
Macs on Ventura. This script swaps the four Qt packages, drops the two
6.12-only split-out packages (QtPdf / QtWebEngine live in Addons on 6.11) and
refreshes their hashes from PyPI. Everything else is kept byte-for-byte.

Usage: python3 scripts/make_macos13_lock.py [--output PATH]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'requirements-macos-x86_64.lock'
DEFAULT_OUT = ROOT / 'requirements-macos13-x86_64.lock'

QT_VERSION = '6.11.3'
QT_PKGS = ('pyside6', 'pyside6-addons', 'pyside6-essentials', 'shiboken6')
DROP_PKGS = ('pyside6-pdf', 'pyside6-webengine')


def pypi_hashes(package: str, version: str) -> list[str]:
    url = f'https://pypi.org/pypi/{package}/{version}/json'
    with urllib.request.urlopen(url, timeout=60) as response:
        data = json.load(response)
    hashes = sorted({entry['digests']['sha256'] for entry in data['urls']})
    if not hashes:
        raise RuntimeError(f'no wheels found for {package}=={version}')
    return hashes


def parse(text: str) -> list[tuple[str, list[str]]]:
    """Split a hash lock into (requirement line, hashes) blocks."""
    blocks: list[tuple[str, list[str]]] = []
    head: str | None = None
    hashes: list[str] = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if line.startswith('    --hash='):
            if head is None:
                raise RuntimeError('hash before requirement')
            hashes.append(line.strip().rstrip('\\').strip())
        else:
            if head is not None:
                blocks.append((head, hashes))
            head = line.rstrip('\\').strip()
            hashes = []
    if head is not None:
        blocks.append((head, hashes))
    return blocks


def render(blocks: list[tuple[str, list[str]]]) -> str:
    out: list[str] = [
        '# Generated by scripts/make_macos13_lock.py for macOS 13 (Ventura) on Intel x86_64.',
        '# Derived from requirements-macos-x86_64.lock; Qt/PySide6 pinned to 6.11.3',
        '# (macosx_13_0_universal2). Install with: pip install --require-hashes -r <this file>',
        '',
    ]
    for head, hashes in blocks:
        out.append(head + ' \\')
        for i, digest in enumerate(hashes):
            suffix = ' \\' if i < len(hashes) - 1 else ''
            out.append('    ' + digest + suffix)
    return '\n'.join(out) + '\n'


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument('--output', type=Path, default=DEFAULT_OUT)
    a = p.parse_args()
    blocks = parse(SOURCE.read_text(encoding='utf-8'))
    result: list[tuple[str, list[str]]] = []
    seen: set[str] = set()
    for head, hashes in blocks:
        name = head.split('==')[0].strip().lower()
        if name in DROP_PKGS:
            continue
        if name in QT_PKGS:
            digest_lines = [f'--hash=sha256:{h}' for h in pypi_hashes(name, QT_VERSION)]
            result.append((f'{name}=={QT_VERSION}', digest_lines))
            seen.add(name)
        else:
            result.append((head, hashes))
    missing = set(QT_PKGS) - seen
    if missing:
        raise RuntimeError(f'source lock lacks Qt packages: {sorted(missing)}')
    a.output.write_text(render(result), encoding='utf-8')
    print('wrote', a.output, '| blocks:', len(result))


if __name__ == '__main__':
    main()
